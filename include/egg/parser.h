#ifndef EGG_PARSER_H
#define EGG_PARSER_H

/**
 * @file parser.h
 * @brief Публичный контракт синтаксического анализатора Egg 0.1; C++17.
 * @details Только объявления; реализация рекурсивным спуском добавляется отдельно.
 * Библиотека не читает файлы, не печатает сообщения и не завершает процесс.
 */

#include "egg/ast.h"
#include "egg/lexer.h"

#include <optional>
#include <string>
#include <variant>
#include <vector>

namespace egg {

enum class ParseErrorCode {
    UnexpectedToken,   ///< Токен не допускается в текущей позиции грамматики.
    UnexpectedEnd,     ///< EOF до завершения обязательной конструкции.
    ChainedComparison, ///< Повторный оператор сравнения без разделяющих скобок.
    InvalidTokenStream ///< Отсутствующий, повторный или преждевременный EOF.
};

struct ParseDiagnostic {
    ParseErrorCode code;
    std::string source_name;
    SourceRange range;               ///< Проблемный токен; для отсутствующего EOF — конец потока.
    std::string message;             ///< Формулировка не является стабильной частью API.
    std::optional<TokenKind> actual; ///< nullopt, если в позиции нет токена.
    /// Возможные ожидаемые категории; может быть пустым для ошибки потока
    /// или запрета цепочки сравнений. Порядок не является частью контракта.
    std::vector<TokenKind> expected;
};

/** @brief Либо полное владеющее дерево, либо первая ошибка; частичного AST нет. */
using ParseResult = std::variant<ast::Program, ParseDiagnostic>;

/**
 * @brief Синтаксический анализатор одного потока токенов.
 * @details Вход — tokens из успешного LexResult. Парсер владеет снимком потока;
 * строки и узлы результата независимы от его времени жизни.
 *
 * Проверяет грамматику docs/egg-spec-v0.1.md, включая единый уровень сравнений:
 * без скобок допускается только один из == != < <= > >=. Арифметика, && и ||
 * группируются слева, унарные операции — справа. Присваивание не выражение.
 * Объявление с именем типа распознаётся по IDENT IDENT; vector<T> различается
 * по следующему токену: IDENT для объявления, [ для литерала.
 *
 * Не разрешает имена, не вычисляет типы и значения и не проверяет диапазон int64.
 * Допустимость места хранения, вызовов и выражений-операторов, контекст this,
 * break/continue/return, точка входа, уникальность объявлений и ограничения
 * встроенных операций проверяются последующим семантическим анализом.
 */
class Parser {
public:
    /**
     * @brief Сохранить токены и имя источника; разбор пока не выполняется.
     * @param tokens Завершённый поток с ровно одним EOF в конце.
     * Категории, значения, лексемы и позиции токенов должны соответствовать
     * контракту Lexer; повторная проверка лексики не выполняется.
     * @param source_name Имя для дерева и диагностики; передаётся явно,
     * поскольку LexResult не хранит его при успехе.
     * @throws std::bad_alloc При невозможности выделить память.
     */
    explicit Parser(std::vector<Token> tokens, std::string source_name = "<memory>");

    /**
     * @brief Независимый разбор с начала сохранённого потока.
     * @details Сначала проверяется наличие ровно одного конечного EOF.
     * При нарушении возвращается InvalidTokenStream: диапазон первого
     * преждевременного EOF либо нулевой диапазон после последнего токена,
     * если EOF отсутствует. Для пустого потока позиция — {0, 1, 1}.
     * Затем разбор останавливается на первой синтаксической ошибке.
     * Поток из одного EOF даёт пустую Program; наличие main проверяется позднее.
     *
     * Повторные вызовы дают структурно одинаковые результаты. Одновременные
     * вызовы допустимы, если объект не изменяется и не уничтожается.
     * Ошибки синтаксиса возвращаются как ParseDiagnostic, не исключениями.
     * @throws std::bad_alloc При невозможности выделить память.
     * @throws std::length_error При превышении ограничений контейнеров.
     */
    [[nodiscard]] ParseResult parse() const;

private:
    std::vector<Token> tokens_;
    std::string source_name_;
};

} // namespace egg

#endif // EGG_PARSER_H
