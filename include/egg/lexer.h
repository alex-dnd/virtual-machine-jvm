#ifndef EGG_LEXER_H
#define EGG_LEXER_H

/**
 * @file lexer.h
 * @brief Публичный интерфейс библиотеки «Лексер» для Egg 0.1.
 * @details Основан на egg-spec-v0.1-ascii.md. Требует C++17.
 * Здесь объявлены только типы и методы; реализация отсутствует.
 * Библиотека не читает файлы, не выводит сообщения и не завершает процесс.
 */

#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <variant>
#include <vector>

namespace egg {

/** @brief Положение границы токена в исходном UTF-8 тексте. */
struct SourcePosition {
    /** @brief Смещение в байтах от начала исходного файла, начиная с нуля. */
    std::size_t byte_offset;
    /** @brief Номер строки, начиная с единицы. */
    std::size_t line;
    /**
     * @brief Номер столбца в кодовых точках Unicode, начиная с единицы.
     * @details Табуляция занимает один столбец; CRLF — один перенос строки.
     * Начальный BOM входит в byte_offset, но не увеличивает column.
     */
    std::size_t column;
};

/**
 * @brief Полуоткрытый диапазон исходного текста [begin, end).
 * @details Для EOF обе границы совпадают с концом исходного текста.
 * Диапазон литерала включает кавычки и исходные escape-последовательности.
 */
struct SourceRange {
    SourcePosition begin; ///< Первая включённая позиция.
    SourcePosition end;   ///< Первая позиция за диапазоном.
};

/**
 * @brief Все категории токенов Egg 0.1.
 * @details Пробелы, комментарии и начальный BOM токенов не образуют.
 * main, print, println, read_int, read_line, exit, size, empty, push,
 * pop, remove и clear имеют категорию Identifier. Их смысл определяется
 * последующими этапами компиляции. true и false имеют собственные категории.
 */
enum class TokenKind {
    EndOfFile,      ///< Конец исходного текста.
    Identifier,     ///< [A-Za-z_][A-Za-z0-9_]*, кроме ключевых слов.
    IntegerLiteral, ///< Последовательность десятичных цифр без знака.
    CharLiteral,    ///< Один декодированный ASCII-символ в одинарных кавычках.
    TextLiteral,    ///< Последовательность ASCII-символов в двойных кавычках.

    KwClass,       ///< class
    KwConstructor, ///< constructor
    KwFn,          ///< fn
    KwInt,         ///< int
    KwBool,        ///< bool
    KwChar,        ///< char
    KwVector,      ///< vector
    KwVoid,        ///< void
    KwIf,          ///< if
    KwElse,        ///< else
    KwWhile,       ///< while
    KwBreak,       ///< break
    KwContinue,    ///< continue
    KwReturn,      ///< return
    KwThis,        ///< this
    KwTrue,        ///< true
    KwFalse,       ///< false

    LeftBrace,    ///< {
    RightBrace,   ///< }
    LeftParen,    ///< (
    RightParen,   ///< )
    LeftBracket,  ///< [
    RightBracket, ///< ]
    Less,         ///< <
    Greater,      ///< >
    Comma,        ///< ,
    Semicolon,    ///< ;
    Dot,          ///< .
    Assign,       ///< =
    Plus,         ///< +
    Minus,        ///< - (также перед отрицательным числом).
    Star,         ///< *
    Slash,        ///< /
    Percent,      ///< %
    Bang,         ///< !
    Arrow,        ///< ->
    Equal,        ///< ==
    NotEqual,     ///< !=
    LessEqual,    ///< <=
    GreaterEqual, ///< >=
    LogicalAnd,   ///< &&
    LogicalOr     ///< ||
};

/** @brief Декодированное значение символьного литерала. */
struct CharacterValue {
    std::uint8_t ascii; ///< Код ASCII от 0 до 127 включительно.
};

/** @brief Декодированное значение текстового литерала. */
struct TextValue {
    /**
     * @brief Байты ASCII после обработки escape-последовательностей.
     * @details Строка может быть пустой и содержать встроенные NUL.
     * Длина определяется через size(), а не по завершающему нулю.
     */
    std::string ascii;
};

/**
 * @brief Значение литерала, если оно декодируется на этапе лексического анализа.
 * @details CharacterValue используется только для CharLiteral, TextValue —
 * только для TextLiteral; для всех остальных категорий — std::monostate.
 * Целые числа представлены исходной записью Token::lexeme без преобразования
 * в машинный числовой тип и без ограничения количества цифр.
 */
using TokenValue = std::variant<std::monostate, CharacterValue, TextValue>;

/**
 * @brief Токен с исходным написанием, позицией и декодированным значением.
 * @details Владеет своими строками и не ссылается на память Lexer.
 */
struct Token {
    TokenKind kind;      ///< Категория токена.
    SourceRange range;   ///< Диапазон в исходном файле.
    std::string lexeme;  ///< Точная копия исходных байтов; для EOF — пустая строка.
    TokenValue value;    ///< Значение согласно контракту TokenValue.
};

/** @brief Машиночитаемая причина лексической ошибки. */
enum class LexErrorCode {
    InvalidUtf8,          ///< Некорректная UTF-8 последовательность, даже в комментарии.
    UnexpectedCharacter,  ///< Недопустимый символ, в том числе одиночный & или |.
    UnexpectedBom,        ///< BOM вне начала файла, включая комментарии и литералы.
    BareCarriageReturn,   ///< CR без следующего LF вне литерала.
    InvalidIntegerSuffix, ///< ASCII-буква или _ непосредственно после цифр.
    UnterminatedLiteral,  ///< EOF до закрывающей кавычки.
    NewlineInLiteral,     ///< Физический LF или CR внутри литерала.
    NonAsciiInLiteral,    ///< Не-ASCII кодовая точка внутри литерала.
    NonPrintableInLiteral, ///< Непечатный ASCII-символ, записанный без escape.
    InvalidEscape,        ///< Неизвестный escape или незавершённый escape перед EOF.
    InvalidHexEscape,     ///< После обратной косой черты и x нет двух hex-цифр.
    EscapeOutOfAsciiRange, ///< Значение hex-escape превышает 0x7F.
    InvalidCharacterLength ///< После декодирования char содержит не один символ.
};

/** @brief Первая обнаруженная ошибка с данными для диагностики компилятора. */
struct LexDiagnostic {
    LexErrorCode code;      ///< Стабильный код, пригодный для программной обработки.
    std::string source_name; ///< Имя файла или условное имя источника.
    SourceRange range;      ///< Диапазон проблемного фрагмента.
    std::string message;    ///< Человекочитаемая причина; формулировка не часть API.
};

/**
 * @brief Результат полного прохода лексера или остановки на первой ошибке.
 * @details При успехе error пуст, tokens заканчивается ровно одним EOF.
 * Пустой исходник также даёт один EOF. При ошибке error заполнен, tokens
 * содержит только полностью распознанные токены до ошибочного фрагмента,
 * без EOF и без частичного ошибочного токена. Все данные принадлежат результату.
 */
struct LexResult {
    std::vector<Token> tokens;           ///< Токены в порядке исходного текста.
    std::optional<LexDiagnostic> error;  ///< Первая ошибка или std::nullopt.
};

/**
 * @brief Лексический анализатор одного исходного файла Egg 0.1.
 * @details Владеет неизменяемым снимком исходного текста и имени источника.
 * Проверяет лексику, декодирует ASCII-литералы и сохраняет исходные позиции.
 * Не проверяет грамматику, разрешение имён и диапазон int64: в частности,
 * допустимость 9223372036854775808 как непосредственного операнда унарного
 * минуса проверяет последующий этап. Знак минуса всегда отдельный токен.
 *
 * Каждый tokenize() начинает независимый проход с начала снимка.
 * Одновременные вызовы tokenize() для одного объекта допустимы, если объект
 * не изменяется присваиванием и не уничтожается до завершения вызовов.
 */
class Lexer {
public:
    /**
     * @brief Сохранить исходный текст и имя для последующего анализа.
     * @param source Полные байты UTF-8 файла; допускаются начальный BOM,
     * встроенные NUL и некорректные байты для последующей диагностики.
     * @param source_name Имя файла для сообщений или условное имя источника.
     * @post Объект владеет копией или перемещённым содержимым аргументов;
     * время жизни исходных аргументов больше не имеет значения.
     * @throws std::bad_alloc Если не удалось выделить память.
     * @note Конструктор не выполняет лексический анализ и не открывает файл.
     */
    explicit Lexer(std::string source, std::string source_name = "<memory>");

    /**
     * @brief Разбить сохранённый исходный текст на токены.
     * @return Владеющий результат: токены с EOF при успехе либо корректный
     * префикс токенов и первая лексическая диагностика при ошибке.
     * @details Регистр значим. Пропускаются пробелы, табуляции, LF, CRLF,
     * начальный UTF-8 BOM и комментарии до конца строки или EOF.
     * В комментариях разрешён Unicode, в литералах — только печатный ASCII
     * и escape-последовательности из спецификации; их значения декодируются.
     * Выбирается самый длинный допустимый знак; комментарий имеет приоритет
     * над Slash. Два закрывающих знака >, два минуса и два ! остаются
     * отдельными токенами. Hex-escape поглощает ровно две цифры: последующая
     * hex-цифра является обычным символом литерала.
     *
     * Проверки идут слева направо, включая проверку UTF-8 в комментариях.
     * При некорректном UTF-8 диагностика указывает первый ошибочный байт;
     * для учёта конца его диапазона этот байт занимает один столбец.
     * Ошибки состава литерала диагностируются при обнаружении, ошибка длины
     * char — после закрывающей кавычки. EOF после обратной косой черты
     * диагностируется как InvalidEscape.
     * @throws std::bad_alloc При невозможности выделить память.
     * @throws std::length_error Если превышены ограничения стандартных контейнеров.
     * @note Лексические ошибки возвращаются в LexResult::error, не исключениями.
     * Повторные вызовы дают одинаковое содержимое и не меняют объект.
     */
    [[nodiscard]] LexResult tokenize() const;

private:
    std::string source_;      ///< Собственный снимок байтов исходного файла.
    std::string source_name_; ///< Собственное имя источника для диагностики.
};

} // namespace egg

#endif // EGG_LEXER_H
